"""The demo calendar as the Markdown tables website/docs/use/demo-workspace.md shows.

Rendered from :mod:`.calendar`'s own constants, so the page cannot describe a
calendar the warehouse does not run: ``backend/scripts/render_demo_calendar.py``
writes the tables between the page's markers, and
``tests/test_demo_calendar_doc.py`` fails when the page and this disagree.
"""

from __future__ import annotations

from collections.abc import Collection

from tripl.core.demo_warehouse import calendar

BEGIN_MARKER = "<!-- demo-calendar:begin (generated by backend/scripts/render_demo_calendar.py) -->"
END_MARKER = "<!-- demo-calendar:end -->"

_WEEKDAYS = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday")
_PLATFORM_LABELS = {"ios": "iOS", "android": "Android", "web": "web"}
_KIND_LABELS = {
    "spike": "Spike",
    "drop": "Drop",
    "error_burst": "Error burst",
    "type_dip": "Event-type dip",
    "platform_shift": "Platform shift",
}


def _platform(name: str) -> str:
    return _PLATFORM_LABELS.get(name, name)


def _hours(delta_hours: float) -> str:
    return f"{delta_hours:g} h"


def _clock(hours: float) -> str:
    whole = int(hours)
    minutes = round((hours - whole) * 60)
    return f"{whole:02d}:{minutes:02d} UTC"


def _change(kind: str, multiplier: float, platform: str | None) -> str:
    text = f"×{multiplier:g}" if multiplier >= 1 else f"to {round(multiplier * 100)} %"
    if platform:
        text += f", on {_platform(platform)}"
    return text


def _incidents_table() -> list[str]:
    start = _clock(calendar.INCIDENT_START.total_seconds() / 3600)
    lines = [
        f"One incident a day, from {start}, in this rotation (day *n* since the "
        "calendar's epoch takes kind *n* mod 5; each kind cycles through its targets):",
        "",
        "| Kind | Scope | Targets | Lasts | Change |",
        "| --- | --- | --- | --- | --- |",
    ]
    for kind, scope, targets, hours, multiplier, platform in calendar._INCIDENT_KINDS:
        scope_label = "event type" if scope == "event_type" else "event"
        lines.append(
            f"| {_KIND_LABELS.get(kind, kind)} | {scope_label} | "
            f"{', '.join(f'`{target}`' for target in targets)} | {_hours(hours)} | "
            f"{_change(kind, multiplier, platform)} |"
        )
    return lines


def _releases_table() -> list[str]:
    interval_days = calendar.RELEASE_INTERVAL.days
    release_at = _clock(calendar.RELEASE_OFFSET.total_seconds() / 3600)
    beta_days = calendar.BETA_PERIOD.days
    lines = [
        f"A release every {interval_days} days at {release_at}, after a {beta_days}-day "
        f"beta at {calendar.BETA_SHARE * 100:g} % of traffic; half the users have "
        f"updated {calendar.ROLLOUT_MIDPOINT_HOURS:g} hours after release, and "
        f"{calendar.LAGGARD_SHARE * 100:g} % stay behind. Each release breaks one "
        "event, in this rotation:",
        "",
        "| Release | Event | What breaks |",
        "| --- | --- | --- |",
    ]
    for position, (event, kind, kept) in enumerate(calendar.REGRESSION_ROTATION):
        what = (
            "missing in the new version"
            if kind == "missing"
            else f"keeps {round(kept * 100)} % of its volume in the new version"
        )
        lines.append(
            f"| *n* ≡ {position} (mod {len(calendar.REGRESSION_ROTATION)}) | `{event}` | {what} |"
        )
    lines += [
        "",
        f"Every other release also sends `properties.{calendar.PROPERTY_TYPE_CHANGE_KEY}` "
        "as a string instead of a number on "
        f"{_platform(calendar.PROPERTY_TYPE_CHANGE_PLATFORM)}: "
        "the property drift.",
    ]
    return lines


def _recurring_table(drift_fields: Collection[str]) -> list[str]:
    promo_at = _clock(calendar.PROMO_START.total_seconds() / 3600)
    lines = [
        "| What | When | Shows up as |",
        "| --- | --- | --- |",
        f"| *{calendar.PROMO_TITLE}* on `{calendar.PROMO_EVENT}` "
        f"(×{calendar.PROMO_MULTIPLIER:g}) | every {_WEEKDAYS[calendar.PROMO_WEEKDAY]}, "
        f"{promo_at}, {_hours(calendar.PROMO_HOURS)} | an anomaly marked *expected* |",
    ]
    for shift in calendar.MIX_SHIFTS:
        shows = (
            "distribution drift"
            if shift.column in drift_fields
            else f"a change in the `{shift.column}` split"
        )
        lines.append(
            f"| {shift.description[:1].upper()}{shift.description[1:]} (`{shift.column}`) | "
            f"{shift.days} days of every {shift.cycle_days}, from day {shift.offset_days} "
            f"of the cycle | {shows} |"
        )
    for name, every, offset, hour, hours in calendar._UNPLANNED_SCHEDULE:
        lines.append(
            f"| `{name}`, a name no plan documents | every {every} days (day ≡ {offset}), "
            f"{_clock(hour)}, {_hours(hours)} | a shadow event candidate |"
        )
    return lines


def calendar_markdown(drift_fields: Collection[str]) -> str:
    """The generated block, markers included, ending with a newline.

    ``drift_fields`` are the fields the demo watches for distribution drift
    (the seeder's scan config), which decides how a mix shift shows up.
    """
    body = [
        BEGIN_MARKER,
        "",
        "#### Daily incidents",
        "",
        *_incidents_table(),
        "",
        "#### Releases",
        "",
        *_releases_table(),
        "",
        "#### Recurring changes",
        "",
        *_recurring_table(drift_fields),
        "",
        END_MARKER,
    ]
    return "\n".join(body) + "\n"


def replace_block(page: str, drift_fields: Collection[str]) -> str:
    """``page`` with the generated block replaced (the markers must be there)."""
    start = page.index(BEGIN_MARKER)
    end = page.index(END_MARKER) + len(END_MARKER)
    if end < len(page) and page[end] == "\n":
        end += 1
    return page[:start] + calendar_markdown(drift_fields) + page[end:]
