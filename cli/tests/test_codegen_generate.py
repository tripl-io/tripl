def test_an_events_own_override_types_its_token() -> None:
    raw = json.loads((FIXTURES / "model.json").read_text(encoding="utf-8"))
    legacy = next(item for item in raw["event_types"] if item["name"] == "legacy")
    promo = next(event for event in legacy["events"] if "${sheet_id}" in event["identity"])
    promo["overrides"] = {"sheet_id": ["autumn"]}
    model = parse_model(raw)
    legacy_model = model.event_type("legacy")
    assert legacy_model is not None
    event = next(item for item in legacy_model.events if "${" in item.identity)
    assert model.allowed_for(event, "sheet_id") == ("autumn",)
    assert model.allowed("sheet_id") == ("spring", "summer")
    # Absent overrides (an older server) fall back to the variable.
    plain_model = _model()
    plain_legacy = plain_model.event_type("legacy")
    assert plain_legacy is not None
    plain = next(item for item in plain_legacy.events if "${" in item.identity)
    assert plain.overrides == {}
    assert plain_model.allowed_for(plain, "sheet_id") == ("spring", "summer")
    # The list form of overrides reads the same as the mapping form.
    promo["overrides"] = [{"token": "sheet_id", "allowed_values": ["autumn"]}]
    listed = parse_model(raw).event_type("legacy")
    assert listed is not None
    listed_event = next(item for item in listed.events if "${" in item.identity)
    assert model.allowed_for(listed_event, "sheet_id") == ("autumn",)
    config = load(FIXTURES / "check.yml")
    files = {
        item.path.name: item.content
        for item in generate(config, model, "demo", out=Path("out"), languages=["swift"])
    }
    swift = files["LegacyTracking.swift"]
    assert 'case autumn = "autumn"' in swift and 'case spring = "spring"' not in swift


def test_token_and_rule_key_grammar_match_the_backend() -> None:
    from tripl_cli.codegen.model import rule_keys, tokens

    # A token is anything but `}` between `${` and `}`, empty included.
    assert tokens("a_${sheet id}_${x.y-z}_${}") == ["sheet id", "x.y-z", ""]
    # A rule key is `{…}` with at least one character, never a `${…}`'s braces.
    assert rule_keys("{category}:${step}:{label}:{}") == ["category", "label"]
    assert rule_keys("{a b}") == ["a b"]


