def test_literal_parts_merge_before_escaping_so_no_live_interpolation_forms() -> None:
    from tripl_cli.codegen.context import interpolation
    from tripl_cli.codegen.languages import DIALECTS

    ts = DIALECTS["ts"]
    # `$` then an unresolved `{app}`: escaped apart they would spell a live `${app}`.
    text = interpolation(ts, "cost {x} $" + "{app}", {"x": "x"}, braces=True)
    assert text == "`cost ${x} \\${app}`"
    merged = ts.interpolate([(False, "$"), (False, "{app}"), (True, "v")])
    assert merged == "`\\${app}${v}`"


