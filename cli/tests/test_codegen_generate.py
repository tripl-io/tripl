# --- the opt-in compiler check ----------------------------------------------------------
@pytest.mark.skipif(shutil.which("tsc") is None, reason="no TypeScript compiler on PATH")
def test_generated_typescript_compiles(tmp_path: Path) -> None:  # pragma: no cover - opt-in
    """Compiles the TS output, and proves a wrong enum value is a compile error.

    Skipped where ``tsc`` is not installed, which is the CLI's own test
    environment (it depends on httpx alone); run it where Node is available.
    """
    ts_dir = tmp_path / "ts"
    for item in _generate(ts_dir, languages=["ts"]):  # one language: written into ts_dir itself
        item.path.parent.mkdir(parents=True, exist_ok=True)
        item.path.write_text(item.content, encoding="utf-8")
    (ts_dir / "analytics.ts").write_text(
        "export const analytics = { log(..._args: unknown[]): void {} };\n", encoding="utf-8"
    )
    (ts_dir / "ok.ts").write_text(
        "import { log } from './appEvents';\n"
        "import { track } from './legacyTracking';\n"
        "log('home', 'open', 'card');\n"
        "track('promo_sheet_${sheet_id}_shown', { sheet_id: 'spring' });\n"
        "track('checkout:start', {});\n",
        encoding="utf-8",
    )
    flags = ["--strict", "--noEmit", "--noUnusedLocals", "--target", "es2020", "--module", "es2020"]
    ok = subprocess.run(
        ["tsc", *flags, *(str(path) for path in sorted(ts_dir.glob("*.ts")))],
        capture_output=True,
        text=True,
        check=False,
    )
    assert ok.returncode == 0, ok.stdout + ok.stderr
    (ts_dir / "bad.ts").write_text(
        "import { log } from './appEvents';\nlog('map', 'open', 'card');\n", encoding="utf-8"
    )
    bad = subprocess.run(
        ["tsc", *flags, str(ts_dir / "bad.ts")], capture_output=True, text=True, check=False
    )
    assert bad.returncode != 0
    assert "'\"map\"' is not assignable" in bad.stdout or "map" in bad.stdout
