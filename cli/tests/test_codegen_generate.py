"""``tripl codegen`` generation: golden files per style x language, and the rules behind them.

The fixture (``tests/codegen/model.json`` + ``check.yml``) is a synthetic plan
with one event type per style: ``se`` (structured, through the team wrapper),
``screen`` (screen_view, through the shared destination), ``legacy`` (named)
and ``sd`` (self-describing). Its values are chosen to hit the naming edge
cases: a digit-first value, a reserved word, a variable-backed value, a free
``${token}``, spaces and colons in event names, deprecated and archived events.

Golden files live in ``tests/codegen/golden/<lang>/``. After an intended
change, regenerate them with ``TRIPL_UPDATE_GOLDEN=1`` and review the diff.

No Swift, Kotlin or TypeScript compiler runs here (the CLI test environment has
none; see ``test_generated_typescript_compiles`` for the opt-in TS check), so
the generated code's shape is asserted structurally instead.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from tripl_cli.check.config import load, parse
from tripl_cli.codegen.generate import GeneratedFile, generate
from tripl_cli.codegen.languages import kotlin_string, swift_string, ts_string
from tripl_cli.codegen.model import CodegenModel, parse_model
from tripl_cli.errors import TriplConfigError, TriplError

FIXTURES = Path(__file__).parent / "codegen"
GOLDEN = FIXTURES / "golden"
REVISION = "9b1f0c52-5d0e-4d6a-8a31-2f6c0e7d4a42"
PLAN_HASH = "5e0d4c3b2a19"


def _model() -> CodegenModel:
    return parse_model(json.loads((FIXTURES / "model.json").read_text(encoding="utf-8")))


def _generate(out: Path, config_text: str | None = None, **kwargs: object) -> list[GeneratedFile]:
    if config_text is None:
        config = load(FIXTURES / "check.yml")
    else:
        from tripl_cli.check import yamlish

        config = parse(yamlish.loads(config_text), path=None, base=out)
    return generate(config, _model(), "demo", out=out, **kwargs)  # type: ignore[arg-type]


def _by_name(files: list[GeneratedFile]) -> dict[str, str]:
    return {f"{item.language}/{item.path.name}": item.content for item in files}


# --- golden ------------------------------------------------------------------------
def test_every_style_in_every_language_matches_its_golden_file(tmp_path: Path) -> None:
    files = _generate(tmp_path)
    produced = {f"{item.language}/{item.path.name}": item.content for item in files}
    if os.environ.get("TRIPL_UPDATE_GOLDEN"):
        for relative, content in produced.items():
            target = GOLDEN / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content.encode("utf-8"))
    expected = {
        path.relative_to(GOLDEN).as_posix(): path.read_bytes().decode("utf-8")
        for path in sorted(GOLDEN.rglob("*"))
        if path.is_file()
    }
    assert sorted(produced) == sorted(expected)
    # 4 styles x 3 languages, plus one shared transport file per language.
    assert len(produced) == 15
    for relative, content in produced.items():
        assert content == expected[relative], f"{relative} differs from its golden file"


def test_output_is_deterministic_and_independent_of_server_order(tmp_path: Path) -> None:
    raw = json.loads((FIXTURES / "model.json").read_text(encoding="utf-8"))
    for event_type in raw["event_types"]:
        event_type["events"].reverse()
        event_type["fields"].reverse()
    raw["event_types"].reverse()
    raw["variables"].reverse()
    config = load(FIXTURES / "check.yml")
    shuffled = generate(config, parse_model(raw), "demo", out=tmp_path)
    assert [item.content for item in shuffled] == [item.content for item in _generate(tmp_path)]


