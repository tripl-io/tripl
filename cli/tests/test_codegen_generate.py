def test_the_typescript_is_strict_mode_shaped(tmp_path: Path) -> None:
    """What ``tsc --strict --noUnusedLocals`` would object to, checked without tsc."""
    for name, content in _by_name(_generate(tmp_path)).items():
        if not name.startswith("ts/"):
            continue
        assert ": any" not in content and "<any>" not in content, name
        assert "// @ts-" not in content, name
        imported = re.findall(r"import \{ ([^}]+) \} from", content)
        for group in imported:
            for symbol in (part.strip() for part in group.split(",")):
                uses = len(re.findall(rf"\b{re.escape(symbol)}\b", content))
                assert uses > 1, f"{name} imports {symbol} and never uses it"
        if "const resolvedName" in content:
            assert content.count("resolvedName") > 1, name


