# --- escaping: a plan value is data, never code ----------------------------------------
@pytest.mark.parametrize(
    ("raw", "swift", "kotlin", "ts"),
    [
        ('say "hi"', r'"say \"hi\""', r'"say \"hi\""', "'say \"hi\"'"),
        ("it's", '"it\'s"', '"it\'s"', r"'it\'s'"),
        ("a\\(b)", r'"a\\(b)"', r'"a\\(b)"', r"'a\\(b)'"),
        ("${x}", '"${x}"', r'"\${x}"', "'${x}'"),
        ("line\nbreak", r'"line\nbreak"', r'"line\nbreak"', r"'line\nbreak'"),
        # U+2028 ends a line in a pre-ES2019 JS string literal, and is invisible in every
        # editor: each language spells it as an escape.
        ("\u2028", r'"\u{2028}"', r'"\u2028"', r"'\u2028'"),
    ],
)
def test_string_literals_escape_per_language(raw: str, swift: str, kotlin: str, ts: str) -> None:
    assert swift_string(raw) == swift
    assert kotlin_string(raw) == kotlin
    assert ts_string(raw) == ts


def test_hostile_plan_values_stay_inert(tmp_path: Path) -> None:
    raw = json.loads((FIXTURES / "model.json").read_text(encoding="utf-8"))
    # No `${`: that would make it a plan token, and the field free text (no enum at all).
    hostile = "x\"); drop(); /* */ $boom \\(pwn) `tick` 'q'\nnext"
    raw["event_types"][0]["events"][0]["field_values"]["category"] = hostile
    config = load(FIXTURES / "check.yml")
    literal = {"swift": swift_string, "kotlin": kotlin_string, "ts": ts_string}
    for item in generate(config, parse_model(raw), "demo", out=tmp_path):
        if item.event_type != "se":
            continue
        # The value appears as ONE string literal of the target language...
        assert literal[item.language](hostile) in item.content
        # ...and its line break never reaches the source: `next` never starts a line.
        assert not any(line.lstrip().startswith("next") for line in item.content.splitlines())


