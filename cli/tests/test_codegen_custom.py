# --- the value role in `calls` --------------------------------------------------------
_CALLS_ONLY = """
event_types:
  se:
    calls:
      - function: "Tracker.log"
        args: {category: category, action: action, value: "value:number"}
    codegen:
      style: structured
      languages: [kotlin]
"""


def test_value_role_in_calls_alone_is_not_forwarded(tmp_path: Path) -> None:
    # Without a `transport` the code forwards to TriplDestination, which has no numeric value.
    kotlin = _generate_text(_CALLS_ONLY, tmp_path)["kotlin/SeTracking.kt"]
    assert "Double" not in kotlin


def test_value_role_in_calls_is_forwarded_by_a_bare_function_transport(tmp_path: Path) -> None:
    config = _CALLS_ONLY + '      transport: {kotlin: "Tracker.log"}\n'
    kotlin = _generate_text(config, tmp_path)["kotlin/SeTracking.kt"]
    assert "value: Double? = null" in kotlin
    assert "value = value)" in kotlin


