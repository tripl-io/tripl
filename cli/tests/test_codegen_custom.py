    assert name_forms("Home Screen View", "kotlin") == {
        "upper_snake": "HOME_SCREEN_VIEW",
        "lower_snake": "home_screen_view",
        "camel": "homeScreenView",
        "pascal": "HomeScreenView",
    }
    assert name_forms("class", "swift")["camel"] == "class_"
    assert name_forms("class", "swift")["lower_snake"] == "class_"
    assert name_forms("default", "ts")["camel"] == "default_"
