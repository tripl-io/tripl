@pytest.mark.parametrize(
    ("name", "signature", "forward"),
    [
        (
            "kotlin/SeTracking.kt",
            "fun log(category: Category, action: Action, label: String? = null, "
            "value: Double? = null)",
            "Tracker.log(category = category.value, action = action.value, label = label, "
            "value = value)",
        ),
        (
            "swift/SeTracking.swift",
            "public static func log(category: Category, action: Action, label: String? = nil, "
            "value: Double? = nil)",
            "Tracker.log(category: category.rawValue, action: action.rawValue, label: label, "
            "value: value)",
        ),
        (
            "ts/seTracking.ts",
            "export function log(category: Category, action: Action, label?: string, "
            "value?: number): void",
            "tracker.log(category, action, label, value);",
        ),
    ],
)
def test_value_role_is_an_optional_number_forwarded_as_is(
    tmp_path: Path, name: str, signature: str, forward: str
) -> None:
    args = "{category: category, action: action, label: label, value: 'value:number'}"
    files = _generate_text(
        f"""
event_types:
  se:
    codegen:
      style: structured
      transport:
        swift: {{function: "Tracker.log", args: {args}}}
        kotlin: {{function: "Tracker.log", args: {args}}}
        ts: {{function: "tracker.log", positional: [category, action, label, "value:number"]}}
""",
        tmp_path,
    )
    assert signature in files[name]
    assert forward in files[name]


