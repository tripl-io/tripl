    planned = files["swift/AcmePlanned.swift"]
    assert "label: AcmeLabel.promoSheet), // deprecated" in planned
    assert "label: AcmeLabel.promoSheet2)," in planned
    assert "property: AcmeProperty.class_)" in planned


