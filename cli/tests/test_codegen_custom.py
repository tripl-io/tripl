def test_check_sees_extra_files_and_cleanup_keeps_them(tmp_path: Path) -> None:
    files = _generate(tmp_path)
    extras = [tmp_path / "kotlin" / "AcmeCategory.kt", tmp_path / "swift" / "AcmePlanned.swift"]
    assert all(item in {f.path for f in files} for item in extras)

    first = sync(files, check=False, project=PROJECT)
    assert all(path.exists() for path in extras)
    assert set(extras) <= set(first.created)

    # A second write leaves every extra file in place: none of them is "stale".
    again = sync(_generate(tmp_path), check=False, project=PROJECT)
    assert not again.stale and not again.drifted
    assert all(path.exists() for path in extras)

    # --check reports a missing or edited extra file, and writes nothing.
    extras[0].unlink()
    extras[1].write_text(extras[1].read_text(encoding="utf-8") + "// edit\n", encoding="utf-8")
    checked = sync(_generate(tmp_path), check=True, project=PROJECT)
    assert extras[0] in checked.created and extras[1] in checked.changed
    assert checked.drifted and not extras[0].exists()

    # An extra file the config no longer produces is ours and stale: removed on a write.
    retired = tmp_path / "kotlin" / "AcmeRetired.kt"
    shutil.copy(tmp_path / "kotlin" / "AcmeLabel.kt", retired)
    result = sync(_generate(tmp_path), check=False, project=PROJECT)
    assert result.stale == [retired] and not retired.exists()
    assert all(path.exists() for path in extras)


def test_codegen_command_writes_and_checks_the_extra_files(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    root = tmp_path / "repo"
    (root / ".tripl").mkdir(parents=True)
    (root / ".git").mkdir()
    shutil.copy(CUSTOM / "check.yml", root / ".tripl" / "check.yml")
    shutil.copytree(CUSTOM / "templates", root / "templates")
    shutil.copy(CUSTOM / "model.json", root / "model.json")
    monkeypatch.chdir(root)

    assert main(["codegen", "--model", "model.json"]) == 0
    written = root / "generated" / "kotlin" / "AcmeCategory.kt"
    assert written.read_bytes() == (GOLDEN / "kotlin" / "AcmeCategory.kt").read_bytes()
    assert main(["codegen", "--model", "model.json", "--check"]) == 0

    written.unlink()
    capsys.readouterr()
    assert main(["codegen", "--model", "model.json", "--check"]) == 1
    captured = capsys.readouterr()
    assert "generated/kotlin/AcmeCategory.kt" in captured.out + captured.err


# --- the context ---------------------------------------------------------------------
def test_new_context_keys_are_additive(tmp_path: Path) -> None:
    from tripl_cli.check.config import load as load_config
    from tripl_cli.codegen.context import Target
    from tripl_cli.codegen.generate import target_context

    config = load_config(CUSTOM / "check.yml")
    spec = next(item for item in config.event_types if item.name == "screen")
    model = _model()
    event_type = model.event_type("screen")
    assert spec.codegen is not None and event_type is not None
    target = Target(spec, spec.codegen, event_type, model, PROJECT, vars=config.codegen.vars)
    context = target_context(target, "kotlin")
    for key in ("header", "namespace", "enums", "function", "known", "imports", "event_type"):
        assert key in context
    assert context["vars"]["prefix"] == "Acme"
    plan = context["plan"]
    assert [field["raw"] for field in plan["fields"]] == ["type", "id"]
    assert plan["field"]["type"]["closed"] is True
    assert [value["raw"] for value in plan["field"]["id"]["values"]] == [
        "annual",
        "cart",
        "confirm",
        "main",
        "monthly",
    ]
    paywall = next(event for event in plan["events"] if event["dynamic"])
    assert paywall["value"]["id"]["dynamic"] is True
    assert paywall["tokens"][0]["names"]["camel"] == "paywallPlan"
    assert [item["raw"] for item in plan["combinations"]][-3:] == [
        "Paywall annual",
        "Paywall monthly",
        "Settings",
    ]
    transport = context["transport"]
    assert transport["function"] == "AcmeTracker.trackScreen"
    assert [(arg["label"], arg["role"], arg["param"]) for arg in transport["args"]] == [
        ("type", "field", "type"),
        ("id", "field", "id"),
    ]
    assert context["enums"][0]["cases"][0]["names"]["upper_snake"] == "CHECKOUT"
    assert [param["role"] for param in context["function"]["params"]] == ["field", "field"]


# --- one naming scope for the fields ------------------------------------------------
# Two fields that land on one name, and a plan field called `value` next to the
# numeric `value:number` role.
_COLLIDING_MODEL = {
    "format": "codegen_model",
    "revision": "r",
    "branch": "main",
    "plan_hash": "a1b2c3d4e5f6",
    "variables": [],
    "event_types": [
        {
            "name": "se",
            "display_name": "S",
            "name_rule": "{a-b}:{a_b}",
            "fields": [
                {
                    "name": name,
                    "required": name == "a-b",
                    "type": "string",
                    "values": None,
                    "variable": None,
                }
                for name in ("a-b", "a_b", "value", "default")
            ],
            "events": [
                {
                    "identity": "x:y",
                    "name": "x:y",
                    "status": "active",
                    "field_values": {"a-b": "x", "a_b": "y", "default": "z"},
                    "deprecated": False,
                }
            ],
        }
    ],
}
_FIELD_NAMES = "{{#is_field}}{{target}}={{names.camel}} {{/is_field}}"
_COLLIDING_TEMPLATE = (
    "{{header}}\n"
    "fields: {{#plan.fields}}{{names.camel}} {{/plan.fields}}\n"
    f"params: {{{{#function.params}}}}{_FIELD_NAMES}{{{{/function.params}}}}\n"
    f"args: {{{{#transport.args}}}}{_FIELD_NAMES}{{{{/transport.args}}}}\n"
    "keys: {{plan.field.a_b.raw}} {{plan.field.default.raw}} "
    "{{#plan.events}}{{value.default.raw}}{{/plan.events}}\n"
)


def _colliding(tmp_path: Path, template_text: str, language: str) -> str:
    template = tmp_path / "t.mustache"
    template.write_text(template_text, encoding="utf-8")
    model_path = tmp_path / "model.json"
    model_path.write_text(json.dumps(_COLLIDING_MODEL), encoding="utf-8")
    args = "{n: name, a: 'a-b', b: 'a_b', v: 'value:number', f: 'field:value'}"
    transport = (
        "{function: t.send, positional: [name, 'a-b', 'a_b', 'value:number', 'field:value']}"
        if language == "ts"
        else f"{{function: T.send, args: {args}}}"
    )
    config = f"""
event_types:
  se:
    codegen:
      style: structured
      languages: [{language}]
      transport: {{{language}: {transport}}}
      template: {{{language}: {template}}}
"""
    files = _generate_text(config, tmp_path, _model(model_path))
    return next(content for name, content in files.items() if "Tracking" in name)


@pytest.mark.parametrize("language", ["kotlin", "swift", "ts"])
def test_a_field_has_the_same_names_in_plan_params_and_transport_args(
    tmp_path: Path, language: str
) -> None:
    lines = _colliding(tmp_path, _COLLIDING_TEMPLATE, language).splitlines()[3:]
    default = "default" if language == "kotlin" else "default_"
    assert lines[0] == f"fields: aB aB2 {default} value "
    assert lines[1] == "params: a-b=aB a_b=aB2 value=value "
    assert lines[2] == "args: a-b=aB a_b=aB2 value=value "
    # `plan.field` and `value.` are keyed by the plain name, the same in every language;
    # of `a-b` and `a_b` (both `a_b`) the first field keeps the key.
    assert lines[3] == "keys: a-b default z"


