"""``tripl codegen`` customisation: a team's own tracking shape from custom templates.

The fixture ``tests/codegen/custom/`` (a synthetic plan, ``check.yml`` and the
templates under ``templates/``) rebuilds, with NO dedicated switch, the shapes
a team may already have in its code base:

(a) constant holders instead of enums (``object AcmeCategory { const val … }``),
    for Kotlin and TypeScript one file per plan field (``codegen.files`` with
    ``each: closed_fields``), for Swift in the event type's own file;
(b) a structured event built as the team's own ``AcmeEvent`` value and handed
    on, with Snowplow's numeric ``value`` mapped to the ``value:number`` role;
(c) screen views as one enum of the PLANNED (type, id) pairs (``plan.combinations``);
(d) event-name and property-key constants (``plan.events``, ``plan.fields``).

Goldens live in ``tests/codegen/custom/golden/<lang>/``; regenerate them with
``TRIPL_UPDATE_GOLDEN=1`` after an intended change and review the diff.
"""

from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

import pytest

from tripl_cli.check import yamlish
from tripl_cli.check.config import load, parse
from tripl_cli.cli import main
from tripl_cli.codegen.files import sync
from tripl_cli.codegen.generate import GeneratedFile, generate
from tripl_cli.codegen.model import CodegenModel, parse_model
from tripl_cli.codegen.naming import NameScope, name_forms
from tripl_cli.errors import TriplConfigError

FIXTURES = Path(__file__).parent / "codegen"
CUSTOM = FIXTURES / "custom"
GOLDEN = CUSTOM / "golden"
PROJECT = "acme"


def _model(path: Path = CUSTOM / "model.json") -> CodegenModel:
    return parse_model(json.loads(path.read_text(encoding="utf-8")))


def _generate(out: Path) -> list[GeneratedFile]:
    return generate(load(CUSTOM / "check.yml"), _model(), PROJECT, out=out)


def _by_name(files: list[GeneratedFile]) -> dict[str, str]:
    return {f"{item.language}/{item.path.name}": item.content for item in files}


def _parse(text: str, base: Path) -> object:
    return parse(yamlish.loads(text), path=None, base=base)


def _generate_text(
    config_text: str, base: Path, model: CodegenModel | None = None
) -> dict[str, str]:
    config = parse(yamlish.loads(config_text), path=None, base=base)
    files = generate(config, model or _model(FIXTURES / "model.json"), "demo", out=base / "out")
    return _by_name(files)


# --- golden ------------------------------------------------------------------------
def test_custom_templates_match_their_golden_files(tmp_path: Path) -> None:
    produced = _by_name(_generate(tmp_path))
    if os.environ.get("TRIPL_UPDATE_GOLDEN"):
        for relative, content in produced.items():
            target = GOLDEN / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content.encode("utf-8"))
    expected = {
        path.relative_to(GOLDEN).as_posix(): path.read_bytes().decode("utf-8")
        for path in sorted(GOLDEN.rglob("*"))
        if path.is_file()
    }
    assert sorted(produced) == sorted(expected)
    for relative, content in produced.items():
        assert content == expected[relative], f"{relative} differs from its golden file"


